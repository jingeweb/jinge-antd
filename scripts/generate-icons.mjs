import { icons } from '@iconify-json/ant-design';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';

// Internal component dependencies only. Keep this list explicit so the full icon set never enters
// the runtime bundle. SVG data is distributed under the upstream Ant Design icons' MIT license.
const iconNames = [
  'loading-outlined',
  'info-circle-filled',
  'check-circle-filled',
  'close-circle-filled',
  'exclamation-circle-filled',
  'close-circle-outlined',
  'close-outlined',
  'left-outlined',
  'right-outlined',
  'up-outlined',
  'down-outlined',
  'check-outlined',
  'minus-outlined',
  'plus-outlined',
  'ellipsis-outlined',
  'calendar-outlined',
  'clock-circle-outlined',
  'swap-outlined',
  'caret-right-outlined',
  'caret-down-outlined',
  'user-outlined',
];
const version = JSON.parse(
  await readFile(
    new URL('../node_modules/@iconify-json/ant-design/package.json', import.meta.url),
    'utf8',
  ),
).version;
let source = `// Generated by pnpm generate:icons from @iconify-json/ant-design ${version} (MIT).\n// Internal dependencies: do not re-export these icons from the public entry point.\nimport './style.scss';\n\nexport interface IconProps {\n  className?: string;\n  size?: number | string;\n  color?: string;\n  style?: string;\n  ariaLabel?: string;\n}\nfunction iconStyle(size?: number | string, color?: string, style?: string) {\n  return \`\${size !== undefined ? \`font-size:\${typeof size === 'number' ? \`\${size}px\` : size};\` : ''}\${color ? \`color:\${color};\` : ''}\${style ?? ''}\`;\n}\n`;
for (const name of iconNames) {
  const icon = icons.icons[name];
  if (!icon) throw new Error(`Unknown Ant Design icon: ${name}`);
  const component =
    'AntDesign' +
    name
      .split('-')
      .map((word) => word[0].toUpperCase() + word.slice(1))
      .join('');
  // Jinge writes SVG attributes as given: preserve native names such as fill-rule.
  const body = icon.body;
  source += `\nexport function ${component}(props: IconProps) {\n  return (\n    <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em"\n      viewBox="0 0 ${icon.width ?? icons.width ?? 16} ${icon.height ?? icons.height ?? 16}"\n      className={\`ja-icon \${props.className ?? ''}\`}\n      style={iconStyle(props.size, props.color, props.style)}\n      role={props.ariaLabel ? 'img' : undefined} aria-label={props.ariaLabel}\n      aria-hidden={props.ariaLabel ? undefined : true} focusable="false">\n      ${body}\n    </svg>\n  );\n}\n`;
}
const target = new URL('../src/_icon/index.tsx', import.meta.url);
await writeFile(target, source);
execFileSync(process.execPath, ['node_modules/oxfmt/bin/oxfmt', target.pathname], {
  cwd: new URL('..', import.meta.url),
  stdio: 'inherit',
});
